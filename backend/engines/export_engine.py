import json
import re
from typing import Any, Dict, List


def _make_cite_key(provider: str, external_id: str, year: str) -> str:
    clean = re.sub(r"[^a-zA-Z0-9]+", "_", f"{provider}_{external_id}_{year}").strip("_")
    return clean[:48] or "anveshan_ref"


def _escape_bibtex_text(text: str) -> str:
    """Escape BibTeX/LaTeX special characters (%, &, _, #, $) while preserving valid BibTeX structure."""
    cleaned = text.replace("{", "").replace("}", "")
    return re.sub(r"(?<!\\)([%&_#$])", r"\\\1", cleaned)


def export_literature_bibtex(sources: List[Dict[str, Any]]) -> str:
    if not sources:
        return "% No saved literature sources in ANVESHAN SQLite library yet.\n"
    entries: List[str] = []
    for s in sources:
        year = (s.get("published_date") or "")[:4] or "n.d."
        key = _make_cite_key(s.get("provider", "src"), s.get("external_id", "id"), year)
        authors = " and ".join(_escape_bibtex_text(a) for a in (s.get("authors") or ["Unknown"]))
        title = _escape_bibtex_text(s.get("title") or "Untitled")
        url = s.get("source_url") or ""
        note_text = _escape_bibtex_text(
            f"Provider: {s.get('provider')}; Scope: {s.get('access_scope')}; ID: {s.get('external_id')}"
        )
        entry = (
            f"@misc{{{key},\n"
            f"  title = {{{{{title}}}}},\n"
            f"  author = {{{authors}}},\n"
            f"  year = {{{year}}},\n"
            f"  howpublished = {{\\url{{{url}}}}},\n"
            f"  note = {{{note_text}}}\n"
            f"}}"
        )
        entries.append(entry)
    return "\n\n".join(entries) + "\n"


def generate_experiment_markdown_report(exp: Dict[str, Any]) -> str:
    params_str = json.dumps(exp.get("parameters", {}), indent=2, sort_keys=True)
    versions_str = json.dumps(exp.get("software_versions", {}), indent=2, sort_keys=True)
    output_obj = exp.get("output")
    compact_out = dict(output_obj) if isinstance(output_obj, dict) else output_obj
    if isinstance(compact_out, dict) and "trajectory" in compact_out and isinstance(compact_out["trajectory"], list):
        compact_out["trajectory"] = f"<{len(compact_out['trajectory'])} computed points preserved in SQLite JSON>"
    output_str = json.dumps(compact_out, indent=2, sort_keys=True)

    return (
        f"# ANVESHAN Experiment Evidence Report\n\n"
        f"- **Experiment ID:** `{exp['id']}`\n"
        f"- **Parent Experiment ID:** `{exp.get('parent_experiment_id') or 'None (original run)'}`\n"
        f"- **Timestamp (UTC):** `{exp['created_at']}`\n"
        f"- **Domain:** `{exp['domain']}`\n"
        f"- **Epistemic Classification:** `{exp['epistemic_label']}`\n"
        f"- **Execution Status:** `{exp['status']}`\n"
        f"- **Input SHA-256 Checksum:** `{exp['input_checksum']}`\n"
        f"- **Output SHA-256 Checksum:** `{exp.get('output_checksum') or 'N/A'}`\n"
        f"- **Deterministic Seed:** `{exp.get('seed')}`\n"
        f"- **Reproduction Command:** `{exp['reproduction_command']}`\n\n"
        f"## Research Question\n{exp['research_question']}\n\n"
        f"## Methodology\n{exp['methodology']}\n\n"
        f"## Input Parameters\n```json\n{params_str}\n```\n\n"
        f"## Computed Output & Verification\n```json\n{output_str}\n```\n\n"
        f"## Runtime Environment Versions\n```json\n{versions_str}\n```\n\n"
        f"*Generated by ANVESHAN — Developer by Divyesh Bambhaniya*\n"
    )
